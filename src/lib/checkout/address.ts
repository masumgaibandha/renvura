/** Display names only -- what `Order.shippingAddress.division` stores and validates against. */
export const DIVISION_NAMES: readonly string[] = DIVISIONS.map((division) => division.name);

/** Districts belonging to a division, by division *name* -- what the dependent select and the server both call with. */
export function districtsForDivision(divisionName: string): District[] {
  const division = DIVISIONS.find((entry) => entry.name === divisionName);
  if (!division) return [];
  return DISTRICTS.filter((district) => district.divisionSlug === division.slug);
}

/** Upazilas belonging to a district, by district *name*. */
export function upazilasForDistrict(districtName: string): Upazila[] {
  const district = DISTRICTS.find((entry) => entry.name === districtName);
  if (!district) return [];
  return UPAZILAS.filter((upazila) => upazila.districtSlug === district.slug);
}

/**
 * Whether a division -> district -> upazila combination is a real, correctly
 * nested one -- the server-side half of the dependent-select guarantee
 * (section 6).
 *
 * Each level is checked against its *actual parent*, not merely checked to
 * exist: a well-formed-looking but mismatched submission -- a real district
 * paired with the wrong division, or a real upazila paired with the wrong
 * district -- is rejected exactly like an unknown name would be.
 */
export function isValidLocationHierarchy(
  divisionName: string,
  districtName: string,
  upazilaName: string,
): boolean {
  const division = DIVISIONS.find((entry) => entry.name === divisionName);
  if (!division) return false;

  const district = DISTRICTS.find(
    (entry) => entry.name === districtName && entry.divisionSlug === division.slug,
  );
  if (!district) return false;

  return UPAZILAS.some((entry) => entry.name === upazilaName && entry.districtSlug === district.slug);
}
