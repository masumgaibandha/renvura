/**
 * Bangladesh administrative locations — division -> district -> upazila.
 *
 * Shipping address collection is a dependent three-level select (section 5, 7.7):
 * choosing a division scopes the district options to it, and choosing a
 * district scopes the upazila options to it. The same dataset drives both the
 * client option lists and the server validation (`isValidLocationHierarchy`),
 * so the two cannot drift apart -- there is one canonical source, not a UI
 * copy and a server copy.
 *
 * **Source and accuracy.** Sourced from the widely-used `bd_geo_code` dataset
 * (github.com/nuhil/bangladesh-geocode), itself derived from Bangladesh
 * National Portal data: 8 divisions, 64 districts, 494 upazilas. A small,
 * deliberate set of names was updated to the current official English
 * spelling where the source still carried a pre-2018-gazette name
 * (division-level "Chattagram" -> "Chattogram", matching the district level
 * which the source already had current; "Barisal" -> "Barishal"; "Comilla" ->
 * "Cumilla"; "Coxsbazar" -> "Cox's Bazar" -- applied consistently at every
 * level, including the affected Sadar upazilas). Nothing else was altered,
 * added or guessed -- this is public administrative geography, not
 * founder-approved business data, but it must still be accurate rather than
 * invented (D-12's spirit applies even where the letter is about business
 * claims).
 *
 * District and division names are each globally unique. **Upazila names are
 * not** -- nine names (e.g. "Kaliganj") recur across different districts, so
 * upazila identity for lookups is always the (district, name) pair, never the
 * name alone; `slug` is namespaced by district for exactly this reason.
 *
 * This stays a local, generated, versioned dataset rather than a runtime
 * dependency or a live API call during checkout (section 5) -- no new package
 * earns its weight for eight divisions worth of static reference data.
 *
 * **One deliberate addition on top of the source data: a "Dhaka City" entry
 * under the Dhaka district's upazilas.** The source dataset stops at upazila
 * granularity, and Dhaka's five upazilas (Savar, Dhamrai, Keraniganj,
 * Nawabganj, Dohar) are its outlying, semi-rural areas -- the city core
 * itself (Dhaka North + South City Corporation) is administered through
 * thanas, a different, finer level the source has no entries for at all. Left
 * as-is, a customer who actually lives in central Dhaka would have had no
 * upazila to select. "Dhaka City" is added as a normal upazila-shaped entry
 * (same shape, same lookup functions, no special-casing anywhere else) so
 * that gap is filled with one clearly-named, real, commonly-used designation
 * -- not dozens of invented or guessed thana entries, which the delivery
 * pricing decision (a flat Dhaka-City-vs-elsewhere split, not a thana-by-thana
 * one) does not need. See `@/lib/checkout/delivery` for where this becomes
 * the delivery-pricing classification.
 */

